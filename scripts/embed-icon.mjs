// Embeds assets/icon.png in src/icon.ts so every host (Node, Deno Deploy,
// Docker) can serve it without reading files at runtime.
//   node scripts/embed-icon.mjs

import { readFile, writeFile } from 'node:fs/promises';

const png = await readFile('assets/icon.png');
await writeFile(
  'src/icon.ts',
  `// Generated by scripts/embed-icon.mjs from assets/icon.png (512×512). Do not edit.\n` +
    `export const ICON_PNG_BASE64 = '${png.toString('base64')}';\n`,
);
console.log(`embedded assets/icon.png (${png.length} bytes) in src/icon.ts`);
