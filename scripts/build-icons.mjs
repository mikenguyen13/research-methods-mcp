// Renders assets/icon.svg into every icon the server and the listings use, and
// embeds them in src/icon.ts so every host serves them without reading files:
//   - favicon.ico with 16, 32, and 48 px images (PNG-compressed ICO entries)
//   - PNGs at 16, 32, 180 (Apple touch), 192, and 512 px, plus the SVG itself
//   - assets/icon.png (512) and assets/icon-400.png (400, for the Cline marketplace)
//   - a 1200x630 social preview image (assets/og.png) for link previews
//   - assets/icon-square.png (512, edge-to-edge navy, for avatars and directories
//     that crop to a circle or round the corners themselves)
//   node scripts/build-icons.mjs

import { readFile, writeFile } from 'node:fs/promises';
import { Resvg } from '@resvg/resvg-js';

const svg = await readFile('assets/icon.svg', 'utf8');
const png = (source, width) => new Resvg(source, { fitTo: { mode: 'width', value: width } }).render().asPng();

const sizes = { 16: png(svg, 16), 32: png(svg, 32), 48: png(svg, 48), 180: png(svg, 180), 192: png(svg, 192), 400: png(svg, 400), 512: png(svg, 512) };

/** ICO container holding PNG images (supported by every current browser and favicon service). */
function ico(images) {
  const header = Buffer.alloc(6 + 16 * images.length);
  header.writeUInt16LE(0, 0); // reserved
  header.writeUInt16LE(1, 2); // type: icon
  header.writeUInt16LE(images.length, 4);
  let offset = header.length;
  images.forEach(([size, data], i) => {
    const e = 6 + 16 * i;
    header.writeUInt8(size >= 256 ? 0 : size, e);
    header.writeUInt8(size >= 256 ? 0 : size, e + 1);
    header.writeUInt8(0, e + 2); // palette
    header.writeUInt8(0, e + 3); // reserved
    header.writeUInt16LE(1, e + 4); // color planes
    header.writeUInt16LE(32, e + 6); // bits per pixel
    header.writeUInt32LE(data.length, e + 8);
    header.writeUInt32LE(offset, e + 12);
    offset += data.length;
  });
  return Buffer.concat([header, ...images.map(([, data]) => data)]);
}

const favicon = ico([[16, sizes[16]], [32, sizes[32]], [48, sizes[48]]]);

// Social preview: icon, name, and one line of description on the brand navy.
const iconBody = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
const og = `<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="630" viewBox="0 0 1200 630">
  <rect width="1200" height="630" fill="#f4f6f9"/>
  <rect x="0" y="0" width="1200" height="12" fill="#22385c"/>
  <g transform="translate(80 171) scale(0.56)">${iconBody}</g>
  <text x="408" y="272" font-family="Segoe UI, Helvetica Neue, Arial, sans-serif" font-size="56" font-weight="700" fill="#18202c">Research Methods Library</text>
  <text x="408" y="334" font-family="Segoe UI, Helvetica Neue, Arial, sans-serif" font-size="28" fill="#45506a">Study designs, assumptions, R and Python code,</text>
  <text x="408" y="374" font-family="Segoe UI, Helvetica Neue, Arial, sans-serif" font-size="28" fill="#45506a">and citations for AI assistants (MCP)</text>
  <text x="408" y="456" font-family="Consolas, Menlo, monospace" font-size="24" fill="#2b5a8f">research-methods-mcp.vercel.app/mcp</text>
</svg>`;
const ogPng = new Resvg(og, { font: { loadSystemFonts: true, defaultFontFamily: 'Arial' } }).render().asPng();

// Square variant: the navy fills the canvas and the artwork (bounding box 92..420 x
// 112..420) is scaled to 0.8 about its centre, so a circular crop keeps a margin.
const glyph = iconBody.replace(/<rect x="15"[^>]*\/>/, '');
const square = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512"><rect width="512" height="512" fill="#22385c"/><g transform="translate(256 256) scale(0.8) translate(-256 -266)">${glyph}</g></svg>`;

await writeFile('assets/icon.png', sizes[512]);
await writeFile('assets/icon-400.png', sizes[400]);
await writeFile('assets/icon-square.png', png(square, 512));
await writeFile('assets/og.png', ogPng);

const b64 = (b) => Buffer.from(b).toString('base64');
await writeFile(
  'src/icon.ts',
  `// Generated by scripts/build-icons.mjs from assets/icon.svg. Do not edit.\n` +
    `export const ICON_SVG = ${JSON.stringify(svg.trim())};\n` +
    `export const FAVICON_ICO_BASE64 = '${b64(favicon)}';\n` +
    `export const ICON_PNG_BASE64: Record<16 | 32 | 180 | 192 | 512, string> = {\n` +
    [16, 32, 180, 192, 512].map((s) => `  ${s}: '${b64(sizes[s])}',`).join('\n') +
    `\n};\nexport const OG_PNG_BASE64 = '${b64(ogPng)}';\n`,
);
console.log(`icons: favicon.ico ${favicon.length} B, icon.png ${sizes[512].length} B, og.png ${ogPng.length} B`);
